test('Define deleted in another editor exposes its latest revision and can be recovered as a new preflighted resource', async t => {
 const h = await setup(t);
 const original = (await h.service.createPolicy('defines', define())).payload.resource;
 const opened = (await h.request('GET', `/api/defines/editor-context?id=${original.id}`)).json();
 await h.service.deletePolicy('defines', original.id);
 h.calls.length = 0;
 const stale = await h.request('POST', '/api/defines/preview', { ...original, entries: ['203.0.113.0/24'], inventoryRevision: opened.inventoryRevision });
 assert.equal(stale.statusCode, 409); assert.equal(stale.json().code, 'STATE_CONFLICT');
 const before = await h.store.read();
 const response = await h.request('GET', `/api/defines/editor-context?id=${original.id}`);
 assert.equal(response.statusCode, 200, response.body);
 const latest = response.json();
 assert.equal(latest.resource, null); assert.deepEqual(latest.references, []);
 assert.ok(latest.inventoryRevision > opened.inventoryRevision);
 assert.deepEqual(await h.store.read(), before); assert.equal(h.calls.length, 0);
 const { id: _removedId, ...draft } = original;
 const preview = await h.request('POST', '/api/defines/preview', { ...draft, entries: ['203.0.113.0/24'], inventoryRevision: latest.inventoryRevision });
 assert.equal(preview.statusCode, 200, preview.body); const candidate = preview.json();
 assert.equal(candidate.valid, true); assert.notEqual(candidate.resource.id, original.id);
 const saved = await h.request('POST', '/api/defines', previewBody(candidate));
 assert.equal(saved.statusCode, 201, saved.body);
 assert.deepEqual((await h.store.read()).defines.map(d => [d.id, d.entries]), [[candidate.resource.id, ['203.0.113.0/24']]]);
});
