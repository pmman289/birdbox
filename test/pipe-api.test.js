const node = id => ({ id, name: id, transport: "agent", routerId: id === "one" ? "192.0.2.1" : "192.0.2.2", deploymentMode: "include", mainConfigPath: "/etc/bird/bird.conf", generatedConfigPath: "/var/lib/birdbox/generated.conf", socketPath: "/run/bird.ctl" });
const pipe = () => ({ label: "API pipe", name: "api_pipe", nodeIds: ["one"], family: "ipv4", table: { name: "master4", source: "existing" }, peerTable: { name: "api_peer", source: "managed" } });
const fail = (status, message) => { throw Object.assign(new Error(message), { status }); };
async function setup(t) {
  const root = await fs.mkdtemp(path.join(os.tmpdir(), "birdbox-pipe-api-"));
  t.after(() => fs.rm(root, { recursive: true, force: true }));
  const database = new MemoryDatabase();
  await database.createState("inventory", validateInventory({ nodes: [node("one"), node("two")] }));
  const store = new InventoryStore({ database, dataDir: root, nodesPath: path.join(root, "nodes.json"), legacySessionPath: path.join(root, "session.json") });
  await store.initialize();
  const calls = []; const failures = new Map();
  configureAgentBroker({ async dispatch(nodeId, method, params) {
    calls.push({ nodeId, method, params });
    if (failures.has(`${nodeId}:${method}`)) return { ok: false, stdout: "", stderr: failures.get(`${nodeId}:${method}`) };
    if (method === "bird.protocol") return { ok: true, stdout: "1002-api_pipe Pipe --- up 00:00\n1006-  Channel main\n    Table: master4\n    Peer table: api_peer\n    Routes: 0 imported, 1 exported", stderr: "" };
    if (method === "bird.routes") return { ok: true, stdout: `Table ${params.table}:\n198.51.100.0/24 blackhole [original_static 00:00] * (200)\n Type: static univ`, stderr: "" };
    return { ok: true, stdout: "", stderr: "" };
  } });
  t.after(() => configureAgentBroker(null));
  const lock = operation => database.withLock("pipe_test", operation);
  const deploymentService = new DeploymentService({ database, store, withDeploymentLock: lock, configForNode: configBundleForNode, emptyConfigForNode: () => ({ main: "", resources: [] }), findNode, validationError: (_config, diagnostic) => String(diagnostic), addEvent: () => {}, fail });
  await deploymentService.initialize();
  let sequence = 0;
  const service = createResourceApplicationService({ store, deploymentService, nodeOnboarding: {}, sessions: {}, withDeploymentLock: lock, makeId: prefix => `${prefix}_${++sequence}`, addEvent: () => ({}), getEvents: () => [] });
  const app = Fastify();
  app.setErrorHandler((error, _request, reply) => reply.code(error.status ?? 500).send({ error: error.message, code: error.code }));
  const options = { authStore: { isAuthenticated: async token => token === "test" }, secureCookieSetting: false };
  await app.register(mutationRoutes, { ...options, service, agentBroker: {} });
  await app.register(sessionRuntimeRoutes, { ...options, store });
  t.after(() => app.close());
  const request = (method, url, payload) => app.inject({ method, url, payload, headers: { cookie: "birdbox_session=test" } });
  // Cookie name follows the shared authentication contract.
  return { database, store, calls, failures, service, deploymentService, request, app, lock };
}
test("Pipe API preview is read-only; CRUD uses preflight and old/new scope union", async t => {
  const h = await setup(t);
  assert.equal((await h.app.inject({ method: "POST", url: "/api/pipes", payload: pipe() })).statusCode, 401);
  const before = await h.store.read();
  const preview = await h.service.previewPipe(pipe());
  assert.equal(preview.payload.valid, true); assert.deepEqual(await h.store.read(), before);
  assert.deepEqual(h.calls.map(c => c.method), ["bird.stage"]);
  const created = await h.request("POST", "/api/pipes", pipe()); assert.equal(created.statusCode, 201, created.body);
  const id = created.json().resource.id;
  assert.equal(h.calls.filter(c => c.method === "bird.stage").at(-1).params.config, preview.payload.configs[0].config);
  h.calls.length = 0;
  const changed = await h.request("PUT", `/api/pipes/${id}`, { nodeIds: ["two"] }); assert.equal(changed.statusCode, 200, changed.body);
  assert.deepEqual(h.calls.filter(c => c.method === "bird.stage").map(c => c.nodeId).sort(), ["one", "two"]);
  assert.doesNotMatch(h.calls.find(c => c.nodeId === "one").params.config, /protocol pipe/);
  assert.match(h.calls.find(c => c.nodeId === "two").params.config, /protocol pipe/);
  const disabled = await h.request("PUT", `/api/pipes/${id}`, { enabled: false }); assert.equal(disabled.statusCode, 200);
  assert.match(h.calls.filter(c => c.method === "bird.stage").at(-1).params.config, /ipv4 table api_peer/);
  assert.doesNotMatch(h.calls.filter(c => c.method === "bird.stage").at(-1).params.config, /protocol pipe/);
  const removed = await h.request("DELETE", `/api/pipes/${id}`); assert.equal(removed.statusCode, 200);
  assert.doesNotMatch(h.calls.filter(c => c.method === "bird.stage").at(-1).params.config, /api_peer/);
  assert.equal((await h.deploymentService.readJournal()).active, null);
});
test("Pipe preview isolates node failures; invalid saves and apply failures preserve inventory and rollback", async t => {
  const h = await setup(t); const before = await h.store.read();
  h.failures.set("two:bird.stage", "node unavailable");
  const preview = await h.service.previewPipe({ ...pipe(), nodeIds: null });
  assert.equal(preview.payload.valid, false); assert.deepEqual(preview.payload.configs.map(n => n.validation.ok), [true, false]);
  await assert.rejects(() => h.service.createPipe({ ...pipe(), nodeIds: null }), /node unavailable/);
  assert.deepEqual(await h.store.read(), before); assert.ok(!h.calls.some(c => c.method === "bird.apply"));
  h.failures.clear(); h.calls.length = 0; h.failures.set("two:bird.apply", "apply failed");
  await assert.rejects(() => h.service.createPipe({ ...pipe(), nodeIds: null }), /apply failed/);
  assert.deepEqual(await h.store.read(), before);
  assert.deepEqual(h.calls.filter(c => c.method === "bird.rollback").map(c => c.nodeId), ["two", "one"]);
  assert.equal((await h.deploymentService.readJournal()).active, null);
  h.failures.clear(); assert.equal((await h.service.createPipe(pipe())).status, 201);
});
test("Pipe runtime and table queries isolate errors and resolve only saved tables", async t => {
  const h = await setup(t); const result = await h.service.createPipe({ ...pipe(), nodeIds: null }); const id = result.payload.resource.id;
  h.failures.set("two:bird.protocol", "Agent offline");
  const runtime = await h.request("GET", `/api/pipes/${id}/runtime`); assert.equal(runtime.statusCode, 200, runtime.body);
  assert.deepEqual(runtime.json().nodes.map(n => n.state), ["up", "error"]); assert.ok(runtime.json().lastCheckedAt); assert.ok(runtime.json().nodes.every(n => n.lastCheckedAt));
  h.failures.set("one:bird.protocol", "No protocols match");
  assert.equal((await h.request("GET", `/api/pipes/${id}/runtime`)).json().nodes[0].state, "not_configured");
  const routes = await h.request("GET", `/api/pipes/${id}/routes?nodeId=one&side=peer&target=198.51.100.1`);
  assert.equal(routes.statusCode, 200, routes.body); assert.match(routes.json().routes[0].summary, /original_static/);
  const rpc = h.calls.filter(c => c.method === "bird.routes").at(-1).params;
  assert.equal(rpc.table, "api_peer"); assert.equal(rpc.target, "198.51.100.1"); assert.equal(rpc.protocolName, undefined); assert.equal(rpc.direction, undefined);
  assert.equal((await h.request("GET", `/api/pipes/${id}/routes?nodeId=one&side=peer&target=1.1.1.1;shutdown`)).statusCode, 400);
  assert.equal((await h.request("GET", `/api/pipes/${id}/routes?nodeId=one&side=arbitrary`)).statusCode, 400);
  assert.equal((await h.request("GET", `/api/pipes/${id}/routes?nodeId=missing&side=primary`)).statusCode, 404);
  await h.service.updatePipe(id, { enabled: false });
  h.calls.length = 0; assert.equal((await h.request("GET", `/api/pipes/${id}/runtime`)).json().nodes[0].state, "disabled"); assert.equal(h.calls.length, 0);
});
test("Pipe policy deletion protection includes disabled pipes and CAS failure rolls back", async t => {
  const h = await setup(t);
  await h.service.createPolicy("filters", { label: "Filter", name: "pipe_filter", source: "filter pipe_filter { accept; }", nodeIds: null });
  const filterId = (await h.store.read()).filters[0].id;
  const result = await h.service.createPipe({ ...pipe(), enabled: false, exportPolicy: { mode: "custom", filterId } });
  await assert.rejects(() => h.service.deletePolicy("filters", filterId), /Pipe/);
  const before = await h.store.read();
  h.store.replace = async () => { throw Object.assign(new Error("revision conflict"), { code: "STATE_CONFLICT", status: 409 }); };
  await assert.rejects(() => h.service.updatePipe(result.payload.resource.id, { enabled: true }), e => e.code === "STATE_CONFLICT");
  assert.deepEqual(await h.store.read(), before); assert.equal((await h.deploymentService.readJournal()).active, null);
});
